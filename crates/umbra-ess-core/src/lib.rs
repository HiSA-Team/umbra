//! umbra-ess-core — the Enclave Swapping Set (ESS) cache logic, carved out of
//! `src/kernel/src/common/ess.rs` for issue #58 so it can be machine-checked.
//!
//! This is the REAL logic (copied verbatim from the kernel), not a re-model.
//! It is `#![no_std]` with **zero `unsafe`**: the hardware seams (DMA fetch,
//! HMAC/AES, MPCBB/RISAF slot flips, trap-fill) live in the per-platform boot
//! crates and are NOT here — they are the opaque boundary of the model.
//!
//! Phase 3b will switch `kernel::common::ess` to re-export from this crate so
//! the firmware and the extracted Coq model share a single source of truth.
#![no_std]

